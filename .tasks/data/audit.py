"""Read-only audit of .tasks/init/ash_collection.json -> .tasks/data/audit.md.

Python 3 stdlib only. Deterministic: no timestamps, every listing sorted.
Run from anywhere: python3 -I .tasks/data/audit.py
"""
import json
import os
import re
import unicodedata
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "init", "ash_collection.json")
OUT = os.path.join(HERE, "audit.md")

NUMERIC = re.compile(r"^\d+$")
SMALL_RE = re.compile(r"^https://images\.pokemontcg\.io/([^/]+)/([^/]+)\.png$")
LARGE_RE = re.compile(r"^https://images\.pokemontcg\.io/([^/]+)/([^/]+)_hires\.png$")
# Unicode that is easy to confuse with ASCII or is invisible.
ODD_CHARS = {
    " ": "NBSP", "‘": "left single quote", "’": "right single quote",
    "“": "left double quote", "”": "right double quote", "–": "en dash",
    "—": "em dash", "…": "ellipsis", "​": "zero-width space",
    "﻿": "BOM", "­": "soft hyphen", "′": "prime", "″": "double prime",
}

lines = []


def out(s=""):
    lines.append(s)


def q(v):
    """Render a value unambiguously (shows whitespace and unicode)."""
    return "`" + json.dumps(v, ensure_ascii=False) + "`"


def jtype(v):
    if v is None:
        return "null"
    return {bool: "bool", int: "int", float: "float", str: "str", list: "list", dict: "dict"}[type(v)]


def is_empty(v):
    return v is None or v == "" or v == [] or v == {}


def ex(ids):
    ids = sorted(set(ids))
    if not ids:
        return ""
    more = f" (+{len(ids) - 5} more)" if len(ids) > 5 else ""
    return " e.g. " + ", ".join(ids[:5]) + more


def ranked(counter):
    return sorted(counter.items(), key=lambda kv: (-kv[1], str(kv[0])))


def vocab(title, counter, examples=None):
    """Print a vocabulary sorted by (-count, value)."""
    out(f"**{title}** ({len(counter)} distinct, {sum(counter.values())} total)")
    out()
    for k, c in ranked(counter):
        tail = ex(examples[k]) if examples is not None else ""
        out(f"- {q(k)}: {c}{tail}")
    out()


def finding(label, ids):
    ids = sorted(set(ids))
    out(f"- {label}: **{len(ids)}**{ex(ids)}")


def lengths(label, lists):
    out(f"- {label}: " + ", ".join(f"{k}: {c}" for k, c in sorted(Counter(len(v) for v in lists).items())))


def walk(v, path, sink):
    """Collect (path, value) for every value nested in v; list items get path + '[]'."""
    sink.append((path, v))
    if isinstance(v, list):
        for x in v:
            walk(x, path + "[]", sink)
    elif isinstance(v, dict):
        for k in v:
            walk(v[k], path + "." + k, sink)


def split_id(i):
    """Set prefix heuristic: split on the LAST hyphen. None if not clean."""
    if not isinstance(i, str) or "-" not in i:
        return None
    p, s = i.rsplit("-", 1)
    return (p, s) if p and s else None


def main():
    with open(SRC, encoding="utf-8") as f:
        data = json.load(f)
    assert isinstance(data, list) and all(isinstance(x, dict) for x in data)
    total = len(data)
    POKE = "Pokémon"

    out("# Data audit: ash_collection.json")
    out()
    out("Generated by `.tasks/data/audit.py` (read-only; source file unchanged). "
        "Example ids are sorted ascending, first 5 shown. Vocabularies sorted by (-count, value). "
        "Values are shown JSON-encoded so whitespace and unicode are visible.")
    out()

    # ---- 1. Totals and ids
    out("## 1. Totals and ids")
    out()
    out(f"- Total items: **{total}**")
    idc = Counter(x.get("id") for x in data)
    dups = [k for k, c in idc.items() if c > 1]
    finding("Duplicate ids (distinct ids occurring >1 time)", [str(k) for k in dups])
    out(f"- Extra rows caused by duplicate ids: **{sum(idc[k] - 1 for k in dups)}**; unique ids: **{len(idc)}**")
    out("- Copies per duplicated id: " + ", ".join(
        f"{k}x: {c}" for k, c in sorted(Counter(idc[k] for k in dups).items())))
    out("- NOTE: tables and vocabularies count rows (duplicate rows included); bulleted findings with example ids count distinct ids.")
    canon = Counter(json.dumps(x, sort_keys=True) for x in data)
    finding("Items that are exact JSON duplicates of another item",
            [x["id"] for x in data if canon[json.dumps(x, sort_keys=True)] > 1])
    out()

    # ---- 2. Key presence
    keys = sorted({k for x in data for k in x})
    out("## 2. Top-level key presence (union over all items)")
    out()
    out(f"Key union ({len(keys)}): " + ", ".join(keys))
    out()
    out("| key | present | missing | null | \"\" | [] | {} |")
    out("|---|---|---|---|---|---|---|")
    for k in keys:
        vals = [x[k] for x in data if k in x]
        out(f"| {k} | {len(vals)} | {total - len(vals)} | {sum(v is None for v in vals)} | "
            f"{sum(v == '' for v in vals)} | {sum(v == [] for v in vals)} | {sum(v == {} for v in vals)} |")
    out()
    finding("Items with a `set` key (else set info must come from `id`)", [x["id"] for x in data if "set" in x])
    for k in keys:
        ids = [x["id"] for x in data if k in x]
        if len(ids) <= 5:
            finding(f"Rare key `{k}` present on", ids)
    out()

    # ---- 3. Nested fields
    out("## 3. Nested fields")
    out()
    out("### images")
    out()
    vocab("images keys", Counter(k for x in data if isinstance(x.get("images"), dict) for k in x["images"]))
    for sub in ("small", "large"):
        finding(f"images.{sub} missing", [x["id"] for x in data if sub not in (x.get("images") or {})])
        finding(f"images.{sub} empty/null",
                [x["id"] for x in data if sub in (x.get("images") or {}) and is_empty(x["images"][sub])])
    out()

    out("### attacks")
    out()
    with_att = [x for x in data if x.get("attacks")]
    attacks = [(x["id"], a) for x in with_att for a in x["attacks"]]
    out(f"- Cards with non-empty attacks: **{len(with_att)}**; attack objects: **{len(attacks)}**")
    lengths("Attacks per card", [x["attacks"] for x in with_att])
    out()
    vocab("attack object keys", Counter(k for _, a in attacks for k in a))
    out("| attack field | present | missing | empty (null/\"\"/[]) |")
    out("|---|---|---|---|")
    for fld in ("name", "cost", "convertedEnergyCost", "damage", "text"):
        pres = [a[fld] for _, a in attacks if fld in a]
        out(f"| {fld} | {len(pres)} | {len(attacks) - len(pres)} | {sum(is_empty(v) for v in pres)} |")
    out()
    cec = [i for i, a in attacks if "convertedEnergyCost" in a and a["convertedEnergyCost"] != len(a.get("cost") or [])]
    finding(f"Cards with an attack where convertedEnergyCost != len(cost) ({len(cec)} attacks)", cec)
    free = [i for i, a in attacks if not a.get("cost") or a.get("cost") == ["Free"]]
    finding(f"Cards with an attack with no cost or ['Free'] ({len(free)} attacks)", free)
    out()
    vocab("attack cost energy types", Counter(c for _, a in attacks for c in (a.get("cost") or [])))

    out("### abilities, ancientTrait, rules")
    out()
    abil = [(x["id"], a) for x in data for a in (x.get("abilities") or [])]
    out(f"- Cards with abilities: **{sum(1 for x in data if x.get('abilities'))}**; ability objects: **{len(abil)}**")
    out()
    vocab("ability object keys", Counter(k for _, a in abil for k in a))
    vocab("ability.type", Counter(a.get("type") for _, a in abil))
    lengths("rules list length per card", [x["rules"] for x in data if "rules" in x])
    out()

    for fld in ("weaknesses", "resistances"):
        out(f"### {fld}")
        out()
        cards = [x for x in data if x.get(fld)]
        entries = [(x["id"], e) for x in cards for e in x[fld]]
        out(f"- Cards with {fld}: **{len(cards)}**; entries: **{len(entries)}**")
        lengths("Entries per card", [x[fld] for x in cards])
        for sub in ("type", "value"):
            finding(f"{fld}[].{sub} missing", [i for i, e in entries if sub not in e])
            finding(f"{fld}[].{sub} empty", [i for i, e in entries if sub in e and is_empty(e[sub])])
        out()
        vocab(f"{fld} entry keys", Counter(k for _, e in entries for k in e))
        vocab(f"{fld}[].type", Counter(e.get("type") for _, e in entries))
        vocab(f"{fld}[].value", Counter(e.get("value") for _, e in entries))

    out("### legalities")
    out()
    lk = Counter(k for x in data for k in (x.get("legalities") or {}))
    vocab("legalities keys", lk)
    for k in sorted(lk):
        vocab(f"legalities.{k} values", Counter(x["legalities"][k] for x in data if k in (x.get("legalities") or {})))
    vocab("legalities full combinations",
          Counter(json.dumps(sorted((x.get("legalities") or {}).items()), ensure_ascii=False) for x in data))
    finding("Cards with empty/missing legalities", [x["id"] for x in data if not x.get("legalities")])
    out()

    # ---- 4. Types
    out("## 4. JSON type distribution per field")
    out()
    out("All paths, nested included (`[]` = list item). Paths with more than one JSON type are flagged **MIXED** "
        "(`null` counts as a type).")
    out()
    allvals = []  # (id, path, value)
    for x in data:
        for k in x:
            tmp = []
            walk(x[k], k, tmp)
            allvals.extend((x["id"], p, v) for p, v in tmp)
    tdist = defaultdict(Counter)
    for _, p, v in allvals:
        tdist[p][jtype(v)] += 1
    for p in sorted(tdist):
        dist = ", ".join(f"{t}: {c}" for t, c in ranked(tdist[p]))
        out(f"- `{p}`: {dist}{' **MIXED**' if len(tdist[p]) > 1 else ''}")
    out()

    # ---- 5. Odd values
    out("## 5. Odd values")
    out()
    out("### hp")
    out()
    hp_bad, hp_bad_ids = Counter(), defaultdict(list)
    for x in data:
        v = x.get("hp")
        if v is not None and not (isinstance(v, str) and NUMERIC.match(v)):
            hp_bad[v] += 1
            hp_bad_ids[v].append(x["id"])
    out(f"- hp present, non-null, but not purely numeric: **{sum(hp_bad.values())}**")
    out()
    if hp_bad:
        vocab("non-numeric hp values", hp_bad, hp_bad_ids)
    finding("hp key present with null value", [x["id"] for x in data if "hp" in x and x["hp"] is None])
    finding("hp non-null on non-Pokémon supertype", [x["id"] for x in data if x.get("hp") is not None and x.get("supertype") != POKE])
    finding("Pokémon supertype with null/missing hp", [x["id"] for x in data if x.get("hp") is None and x.get("supertype") == POKE])
    hps = sorted(int(x["hp"]) for x in data if isinstance(x.get("hp"), str) and NUMERIC.match(x["hp"]))
    if hps:
        out(f"- numeric hp range: {hps[0]}..{hps[-1]}")
    finding("hp not a multiple of 10", [x["id"] for x in data if isinstance(x.get("hp"), str)
                                        and NUMERIC.match(x["hp"]) and int(x["hp"]) % 10])
    out()

    out("### attack damage formats")
    out()
    dmg_pat, dmg_pat_ids = Counter(), defaultdict(list)
    for i, a in attacks:
        d = a.get("damage", "<missing>")
        pat = re.sub(r"\d+", "N", d) if isinstance(d, str) else jtype(d)
        dmg_pat[pat] += 1
        dmg_pat_ids[pat].append(i)
    vocab("damage patterns (digits replaced by N; `\"\"` = no damage)", dmg_pat, dmg_pat_ids)
    vocab("damage raw values", Counter(a.get("damage", "<missing>") for _, a in attacks))

    out("### level")
    out()
    lv_ids = defaultdict(list)
    for x in data:
        if "level" in x:
            lv_ids[x["level"]].append(x["id"])
    lv = Counter({k: len(v) for k, v in lv_ids.items()})
    nonnum = Counter({k: c for k, c in lv.items() if not (isinstance(k, str) and NUMERIC.match(k))})
    out(f"- level present: {sum(lv.values())}; non-numeric: **{sum(nonnum.values())}**")
    out()
    if nonnum:
        vocab("non-numeric level values", nonnum, lv_ids)
    vocab("level values", lv)

    out("### evolvesFrom / evolvesTo")
    out()
    lengths("evolvesTo list length", [x["evolvesTo"] for x in data if "evolvesTo" in x])
    finding("evolvesTo on non-Pokémon", [x["id"] for x in data if "evolvesTo" in x and x.get("supertype") != POKE])
    finding("evolvesTo contains own name", [x["id"] for x in data if x.get("name") in (x.get("evolvesTo") or [])])
    finding("evolvesFrom equals own name", [x["id"] for x in data if "evolvesFrom" in x and x["evolvesFrom"] == x.get("name")])
    finding("subtype Basic but has evolvesFrom", [x["id"] for x in data if "evolvesFrom" in x and "Basic" in (x.get("subtypes") or [])])
    finding("subtype Stage 1/Stage 2 without evolvesFrom",
            [x["id"] for x in data if {"Stage 1", "Stage 2"} & set(x.get("subtypes") or []) and "evolvesFrom" not in x])
    out()

    out("### nationalPokedexNumbers")
    out()
    npn = [x for x in data if "nationalPokedexNumbers" in x]
    lengths("list length", [x["nationalPokedexNumbers"] for x in npn])
    finding("non-int entries", [x["id"] for x in npn for n in x["nationalPokedexNumbers"]
                                if not isinstance(n, int) or isinstance(n, bool)])
    ints = sorted(n for x in npn for n in x["nationalPokedexNumbers"] if isinstance(n, int))
    if ints:
        out(f"- range: {ints[0]}..{ints[-1]}")
    finding("unsorted lists", [x["id"] for x in npn if x["nationalPokedexNumbers"] != sorted(x["nationalPokedexNumbers"])])
    finding("Pokémon supertype without nationalPokedexNumbers",
            [x["id"] for x in data if x.get("supertype") == POKE and "nationalPokedexNumbers" not in x])
    out()

    out("### flavorText")
    out()
    finding("flavorText containing newline", [x["id"] for x in data if "\n" in (x.get("flavorText") or "")])
    out()

    out("### retreatCost")
    out()
    finding("convertedRetreatCost != len(retreatCost)", [x["id"] for x in data if "convertedRetreatCost" in x
                                                         and x["convertedRetreatCost"] != len(x.get("retreatCost") or [])])
    finding("retreatCost without convertedRetreatCost", [x["id"] for x in data if "retreatCost" in x and "convertedRetreatCost" not in x])
    finding("convertedRetreatCost without retreatCost", [x["id"] for x in data if "convertedRetreatCost" in x and "retreatCost" not in x])
    out()

    out("### Gaps by supertype")
    out()
    finding("rarity missing", [x["id"] for x in data if "rarity" not in x])
    finding("subtypes missing", [x["id"] for x in data if "subtypes" not in x])
    finding("artist missing", [x["id"] for x in data if "artist" not in x])
    finding("Pokémon without types", [x["id"] for x in data if x.get("supertype") == POKE and not x.get("types")])
    finding("types on non-Pokémon", [x["id"] for x in data if x.get("types") and x.get("supertype") != POKE])
    finding("Pokémon without attacks", [x["id"] for x in data if x.get("supertype") == POKE and not x.get("attacks")])
    out()

    out("### String hygiene per field (all nested strings)")
    out()
    by_path = defaultdict(list)
    for i, p, v in allvals:
        if isinstance(v, str):
            by_path[p].append((i, v))
    checks = [
        ("lead/trail whitespace", lambda s: s != s.strip()),
        ("double spaces", lambda s: "  " in s),
        ("newline", lambda s: "\n" in s or "\r" in s),
        ("other control chars", lambda s: any(unicodedata.category(c) == "Cc" and c not in "\n\r" for c in s)),
        ("non-ASCII", lambda s: any(ord(c) > 127 for c in s)),
        ("odd unicode", lambda s: any(c in ODD_CHARS for c in s)),
    ]
    out("Counts are strings (not cards). \"odd unicode\" = " + ", ".join(sorted(set(ODD_CHARS.values()))) + ".")
    out()
    out("| field | strings | " + " | ".join(n for n, _ in checks) + " |")
    out("|---|---|" + "---|" * len(checks))
    for p in sorted(by_path):
        row = [str(sum(1 for _, s in by_path[p] if fn(s))) for _, fn in checks]
        out(f"| `{p}` | {len(by_path[p])} | " + " | ".join(row) + " |")
    out()
    out("Card examples per field and check (non-zero only; counts are cards):")
    out()
    for p in sorted(by_path):
        for n, fn in checks:
            ids = [i for i, s in by_path[p] if fn(s)]
            if ids:
                finding(f"`{p}` {n}", ids)
    out()
    out("Distinct non-ASCII characters per field (occurrences):")
    out()
    for p in sorted(by_path):
        cc = Counter(c for _, s in by_path[p] for c in s if ord(c) > 127)
        if cc:
            out(f"- `{p}`: " + "; ".join(f"{q(c)} U+{ord(c):04X} {unicodedata.name(c, '?')}: {n}" for c, n in ranked(cc)))
    out()

    out("### Numeric-looking string fields containing letters")
    out()
    out("A field is numeric-looking if more than half of its non-empty string values are pure digits.")
    out()
    for p in sorted(by_path):
        vals = [(i, s) for i, s in by_path[p] if s != ""]
        frac = sum(1 for _, s in vals if NUMERIC.match(s)) / len(vals) if vals else 0
        if frac <= 0.5:
            continue
        letters = [(i, s) for i, s in vals if re.search(r"[A-Za-z]", s)]
        other = [(i, s) for i, s in vals if not NUMERIC.match(s) and not re.search(r"[A-Za-z]", s)]
        out(f"- `{p}` ({len(vals)} non-empty, {frac:.1%} pure digits): with letters **{len(letters)}**"
            f"{ex([i for i, _ in letters])}; other non-digit **{len(other)}**{ex([i for i, _ in other])}")
        for label, group in (("letter values", letters), ("other non-digit values", other)):
            vc = Counter(s for _, s in group)
            if vc:
                out(f"  - {label}: " + ", ".join(f"{q(k)}: {c}" for k, c in ranked(vc)))
    out()

    # ---- 6. Vocabularies
    out("## 6. Vocabularies")
    out()
    vocab("supertype", Counter(x.get("supertype") for x in data))
    vocab("subtypes (each)", Counter(s for x in data for s in (x.get("subtypes") or [])))
    vocab("subtypes (combos, source order)", Counter(" + ".join(x["subtypes"]) for x in data if "subtypes" in x))
    vocab("types (each)", Counter(t for x in data for t in (x.get("types") or [])))
    vocab("types (combos, source order)", Counter(" + ".join(x["types"]) for x in data if "types" in x))
    vocab("rarity", Counter(x.get("rarity", "<missing>") for x in data))
    vocab("regulationMark", Counter(x["regulationMark"] for x in data if "regulationMark" in x))
    vocab("retreatCost values (each entry)", Counter(r for x in data for r in (x.get("retreatCost") or [])))
    vocab("convertedRetreatCost", Counter(x["convertedRetreatCost"] for x in data if "convertedRetreatCost" in x))
    out("(legalities, weaknesses and resistances vocabularies are in section 3.)")
    out()

    # ---- 7. Set prefix
    out("## 7. Set prefix derived from id")
    out()
    out("Heuristic: `prefix, suffix = id.rsplit('-', 1)` (split on the LAST hyphen). Clean when the id contains a "
        "hyphen and both parts are non-empty. Suffixes may contain letters (e.g. `swsh12pt5gg-GG01`).")
    out()
    finding("ids without a hyphen or not splitting cleanly", [str(x.get("id")) for x in data if not split_id(x.get("id"))])
    good = [(x, *split_id(x["id"])) for x in data if split_id(x.get("id"))]
    finding("ids with more than one hyphen", [x["id"] for x, _, _ in good if x["id"].count("-") > 1])
    finding("ids with whitespace or uppercase in prefix", [x["id"] for x, p, _ in good if re.search(r"\s", x["id"]) or p != p.lower()])
    out()
    vocab("set prefixes", Counter(p for _, p, _ in good))
    finding("ids whose suffix is not pure digits", [x["id"] for x, _, s in good if not NUMERIC.match(s)])
    out()
    vocab("id suffix patterns (digits -> N)", Counter(re.sub(r"\d+", "N", s) for _, _, s in good))

    out("### number vs id")
    out()
    pn = defaultdict(list)
    for x, p, _ in good:
        pn[(p, x["number"])].append(x["id"])
    coll = {k: v for k, v in pn.items() if len(v) > 1}
    out(f"- (prefix, number) collisions: **{len(coll)}** pairs covering {sum(len(v) for v in coll.values())} items"
        + ex([i for v in coll.values() for i in v]))
    distinct = {k: sorted(set(v)) for k, v in coll.items() if len(set(v)) > 1}
    out(f"- (prefix, number) collisions between DIFFERENT ids: **{len(distinct)}**"
        + ex([i for v in distinct.values() for i in v]))
    finding("number != id suffix after last hyphen", [x["id"] for x, _, s in good if x["number"] != s])
    finding("number != id suffix (case-insensitive)", [x["id"] for x, _, s in good if str(x["number"]).lower() != s.lower()])
    finding("number with leading zero", [x["id"] for x in data if isinstance(x["number"], str) and re.match(r"^0\d", x["number"])])
    out()

    # ---- 8. Images
    out("## 8. Image URLs")
    out()
    out("Expected: small `https://images.pokemontcg.io/<prefix>/<number>.png`, large "
        "`https://images.pokemontcg.io/<prefix>/<number>_hires.png`, with `<prefix>`/`<number>` the id split on the last hyphen.")
    out()
    out("**Reachability was NOT checked: no URL was fetched.**")
    out()
    for sub, rx in (("small", SMALL_RE), ("large", LARGE_RE)):
        urls = [(x["id"], (x.get("images") or {}).get(sub)) for x in data]
        nonconf = [(i, u) for i, u in urls if not (isinstance(u, str) and rx.match(u))]
        out(f"- images.{sub}: conforming **{len(urls) - len(nonconf)}**, non-conforming **{len(nonconf)}**")
        for i, u in sorted(nonconf, key=lambda t: t[0])[:5]:
            out(f"  - {i}: {q(u)}")
        finding(f"images.{sub} not https", [i for i, u in urls if isinstance(u, str) and not u.startswith("https://")])
        hosts = Counter(re.sub(r"^[a-z]+://([^/]+)/.*$", r"\1", u) for _, u in urls if isinstance(u, str))
        out("  - hosts: " + ", ".join(f"{h}: {c}" for h, c in ranked(hosts)))
        mm_id, mm_num = [], []
        for x, p, s in good:
            u = (x.get("images") or {}).get(sub)
            m = rx.match(u) if isinstance(u, str) else None
            if not m:
                continue
            if (m.group(1), m.group(2)) != (p, s):
                mm_id.append(x["id"])
            if (m.group(1), m.group(2)) != (p, x["number"]):
                mm_num.append(x["id"])
        finding(f"images.{sub} `<prefix>/<number>` != id prefix/suffix", mm_id)
        finding(f"images.{sub} `<prefix>/<number>` != id prefix + `number` field", mm_num)
    finding("large URL != small URL with `_hires` inserted",
            [x["id"] for x in data if isinstance((x.get("images") or {}).get("small"), str)
             and isinstance(x["images"].get("large"), str)
             and x["images"]["small"][:-4] + "_hires.png" != x["images"]["large"]])
    dup_small = Counter((x.get("images") or {}).get("small") for x in data)
    out(f"- images.small URLs shared by >1 item: **{sum(1 for c in dup_small.values() if c > 1)}**")
    out()

    # ---- 9. Other
    out("## 9. Other observations")
    out()
    namec = Counter(x["name"] for x in data)
    out(f"- distinct names: **{len(namec)}**; most frequent: " + ", ".join(f"{q(k)}: {c}" for k, c in ranked(namec)[:10]))
    finding("name containing non-ASCII", [x["id"] for x in data if any(ord(c) > 127 for c in x["name"])])
    finding("artist containing non-ASCII", [x["id"] for x in data if any(ord(c) > 127 for c in x.get("artist", ""))])
    out()

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    # self-check
    assert total == 2138, total
    assert os.path.getsize(OUT) > 0
    print(f"wrote {OUT}: {len(lines)} lines, {total} items")


